const router = require('express').Router();
const wrap = require('../utils/asyncHandler');
const methodNotAllowed = require('../middlewares/methodNotAllowed');
const ai = require('../controllers/ai');
router.route('/analyze').post(wrap(ai.analyze)).all(methodNotAllowed('POST'));
router.route('/usages').get(wrap(ai.usages)).all(methodNotAllowed('GET'));
router.route('/usage-summary').get(wrap(ai.usageSummary)).all(methodNotAllowed('GET'));
router.route('/wallet').get(wrap(ai.walletGet)).all(methodNotAllowed('GET'));
router.route('/ledger').get(wrap(ai.ledger)).all(methodNotAllowed('GET'));
module.exports = router;
